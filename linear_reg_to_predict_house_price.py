import pandas as pd
import matplotlib.pyplot as plt
from sklearn.linear_model import LinearRegression
from sklearn.model_selection import train_test_split

data={'square_feet':[1000,1500,2000,2500,3000],
      'price':[200000,250000,300000,350000,400000]}
df=pd.DataFrame(data)
x=df[['square_feet']]
y=df['price']
x_train,x_test,y_train,y_test=train_test_split(x,y,test_size=0.2,random_state=42)
model=LinearRegression()
model.fit(x_train,y_train)
print("----model coefficients----")
print(f"intercept:${model.intercept_:,.2f}")
print(f"slope(coefficient for square feet):${model.coef_[0]:,.2f}per sq.ft\n")
sqft_input=float(input("enter square footage to predict house price:"))
input_df=pd.DataFrame({'square_feet':[sqft_input]})
predicted_price=model.predict(input_df)
print(f"\n predicted price for {sqft_input:.0f}sq.ft=RS{predicted_price[0]:,.2f}")
plt.scatter(x_train,y_train,color='blue',label='training data')
plt.scatter(x_test,y_test,color='pink',label='testing data')
plt.plot(x,model.predict(x),color='red',label='regression line')
plt.xlabel('square feet')
plt.ylabel('price')
plt.title('house price prediction')
plt.legend()
plt.show()